/** Flat lookup of every nav item by href. */
export const navItemByHref: Map<string, NavItem> = (() => {
  const map = new Map<string, NavItem>();
  for (const group of navigation) {
    for (const item of group.items) map.set(item.href, item);
  }
  return map;
})();

/** Looks up an item and its parent group for a pathname. */
export function resolveNav(
  pathname: string,
): { group: NavGroup; item: NavItem } | null {
  const target = pathname === "/" ? "/overview" : pathname;
  for (const group of navigation) {
    for (const item of group.items) {
      if (item.href === target || item.href === pathname) return { group, item };
    }
  }
  return null;
}
